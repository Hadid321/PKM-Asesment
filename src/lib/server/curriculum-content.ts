export function curriculumPackage(subject: import("../subjects").Subject) {
  const topics = CURRICULUM_TOPICS.filter((t) => t.subject === subject);
  const slugs = new Set(topics.map((t) => t.slug));
  return {
    version: CURRICULUM_VERSION,
    topics,
    questions: CURRICULUM_QUESTIONS.filter((q) => slugs.has(q.topic_slug)),
  };
}
